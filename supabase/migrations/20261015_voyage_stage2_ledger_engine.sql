FROM attendance a
WHERE a.award_points > 0
ON CONFLICT (event_key) DO NOTHING;

-- Passport country records are one per resident-country, while the score ledger retains each visit.
WITH countries AS (
  SELECT DISTINCT ON (ga.profile_id, upper(COALESCE(NULLIF(d.country_code,''), CASE WHEN d.code ~* '^[A-Z]{2}$' THEN d.code END)))
         ga.profile_id,
         upper(COALESCE(NULLIF(d.country_code,''), CASE WHEN d.code ~* '^[A-Z]{2}$' THEN d.code END)) AS country_code,
         COALESCE(NULLIF(d.name,''), upper(COALESCE(NULLIF(d.country_code,''), d.code))) AS country_title,
         ga.stamped_at
  FROM public.game_attendance ga
  JOIN public.game_destinations d ON d.id = ga.destination_id
  WHERE upper(COALESCE(NULLIF(d.country_code,''), CASE WHEN d.code ~* '^[A-Z]{2}$' THEN d.code END)) ~ '^[A-Z]{2}$'
  ORDER BY ga.profile_id,
           upper(COALESCE(NULLIF(d.country_code,''), CASE WHEN d.code ~* '^[A-Z]{2}$' THEN d.code END)),
           ga.stamped_at, ga.id
), rule AS (
  SELECT COALESCE((SELECT GREATEST(0, round(value)::integer) FROM public.resident_scoring_rules WHERE key='first_stamp_points'),25) AS points
)
