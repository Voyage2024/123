--    exactly follows DB-side points * multiplier * visit factor, with no client-computed total.
WITH attendance AS (
  SELECT ga.id, ga.profile_id, ga.destination_id, ga.visit_number, ga.stamped_at,
         COALESCE(ga.points,d.points) AS base_points,
         COALESCE(ga.multiplier,d.multiplier) AS multiplier,
         GREATEST(0, round(COALESCE(ga.points,d.points)::numeric * COALESCE(ga.multiplier,d.multiplier) * public.game_visit_factor(ga.visit_number)))::integer AS award_points,
         d.name
  FROM public.game_attendance ga
  JOIN public.game_destinations d ON d.id = ga.destination_id
)
