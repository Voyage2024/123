-- 2. Preserve the existing 1/1.5/2 visit multiplier, now used by the DB ledger trigger.
CREATE OR REPLACE FUNCTION public.game_visit_factor(n integer)
RETURNS numeric
LANGUAGE sql IMMUTABLE PARALLEL SAFE
AS $$
  SELECT CASE WHEN n IS NULL OR n <= 1 THEN 1.0 WHEN n = 2 THEN 1.5 ELSE 2.0 END;
$$;

-- 3. Rebuild the metrics materialization so game_attendance is now reconciled with the ledger.
CREATE OR REPLACE FUNCTION public.resident_refresh_metrics(p_profile_id uuid)
RETURNS void
LANGUAGE plpgsql SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_total integer;
  v_level smallint;
  v_circle text;
BEGIN
  IF p_profile_id IS NULL THEN RETURN; END IF;

  INSERT INTO public.resident_metrics(profile_id)
  VALUES (p_profile_id)
  ON CONFLICT (profile_id) DO NOTHING;

  UPDATE public.resident_metrics rm
  SET total_points = rm.legacy_total_points + COALESCE((SELECT sum(se.points) FROM public.resident_score_events se WHERE se.profile_id = p_profile_id), 0)::integer,
      tour_points = rm.legacy_tour_points + COALESCE((SELECT sum(se.points) FROM public.resident_score_events se WHERE se.profile_id = p_profile_id AND se.category = 'tour'), 0)::integer,
      event_points = COALESCE((SELECT sum(se.points) FROM public.resident_score_events se WHERE se.profile_id = p_profile_id AND se.category = 'event'), 0)::integer,
      stamp_points = rm.legacy_stamp_points + COALESCE((SELECT sum(se.points) FROM public.resident_score_events se WHERE se.profile_id = p_profile_id AND se.category = 'stamp'), 0)::integer,
      achievement_points = COALESCE((SELECT sum(se.points) FROM public.resident_score_events se WHERE se.profile_id = p_profile_id AND se.category = 'achievement'), 0)::integer,
      -- Legacy visit counts are reconciled once during Stage 2; count every attendance row here.
      stamps_count = rm.legacy_stamps_count
        + (SELECT count(*)::integer FROM public.game_attendance ga WHERE ga.profile_id = p_profile_id)
        + (SELECT count(*)::integer FROM public.resident_passport_stamps s WHERE s.profile_id = p_profile_id AND s.activity_id IS NOT NULL),
      destinations_count = rm.legacy_destinations_count
        + (SELECT count(DISTINCT ga.destination_id)::integer FROM public.game_attendance ga WHERE ga.profile_id = p_profile_id)
        + (SELECT count(*)::integer
           FROM public.resident_passport_stamps s
           WHERE s.profile_id = p_profile_id AND s.activity_id IS NOT NULL
             AND NOT EXISTS (
               SELECT 1
               FROM public.game_attendance ga
               JOIN public.game_destinations gd ON gd.id = ga.destination_id
               WHERE ga.profile_id = p_profile_id
                 AND upper(COALESCE(NULLIF(gd.country_code,''), CASE WHEN gd.code ~* '^[A-Z]{2}$' THEN gd.code END)) = upper(s.country_code)
             )),
      combo_points = rm.legacy_combo_points + COALESCE((SELECT sum(se.points) FROM public.resident_score_events se WHERE se.profile_id = p_profile_id AND se.category = 'combo'), 0)::integer,
      combos_completed = rm.legacy_combos_completed + (SELECT count(*)::integer FROM public.resident_achievements ach WHERE ach.profile_id = p_profile_id AND ach.achievement_key LIKE 'combo:%'),
      patronage_points = rm.legacy_patronage_points,
      proteges_count = rm.legacy_proteges_count,
      tours_count = rm.legacy_tours_count + (SELECT count(*)::integer FROM public.resident_activities a WHERE a.profile_id = p_profile_id AND a.activity_type = 'tour'),
      completed_activities = (SELECT count(*)::integer FROM public.resident_activities a WHERE a.profile_id = p_profile_id),
      achievements_count = (SELECT count(*)::integer FROM public.resident_achievements a WHERE a.profile_id = p_profile_id),
      updated_at = now()
  WHERE rm.profile_id = p_profile_id
  RETURNING total_points INTO v_total;

  SELECT gc.level::smallint, gc.key
    INTO v_level, v_circle
  FROM public.game_circles gc
  WHERE gc.min_influence <= COALESCE(v_total, 0)
  ORDER BY gc.min_influence DESC, gc.level DESC
  LIMIT 1;

  IF v_level IS NULL THEN
    v_level := CASE
      WHEN COALESCE(v_total,0) >= 30000 THEN 6
      WHEN COALESCE(v_total,0) >= 15000 THEN 5
      WHEN COALESCE(v_total,0) >= 7500 THEN 4
      WHEN COALESCE(v_total,0) >= 3000 THEN 3
      WHEN COALESCE(v_total,0) >= 1000 THEN 2
      ELSE 1
    END;
    v_circle := CASE v_level WHEN 6 THEN 'black' WHEN 5 THEN 'private' WHEN 4 THEN 'inner' WHEN 3 THEN 'preferred' WHEN 2 THEN 'resident' ELSE 'voyager' END;
  END IF;

  PERFORM set_config('voyage.gamification_internal', 'on', true);
  UPDATE public.profiles
  SET influence_index = GREATEST(COALESCE(v_total, 0), 0),
      level = v_level,
      circle = COALESCE(v_circle, 'voyager')
  WHERE id = p_profile_id AND role = 'resident';
  PERFORM set_config('voyage.gamification_internal', 'off', true);
END;
$function$;

-- 4. Shared server handler used by both completion trigger paths and the repair backfill.
CREATE OR REPLACE FUNCTION public.resident_process_completed_activity_row(p_source_table text, p_source_id uuid)
RETURNS uuid
LANGUAGE plpgsql SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_profile_id uuid;
  v_status text;
  v_hub_id text;
  v_event_id uuid;
  v_label text;
  v_country text;
  v_event_country text;
  v_event_title text;
  v_value numeric(12,2);
  v_complexity numeric(4,2);
  v_completed_by uuid;
  v_completed_at timestamptz;
  v_reliability numeric(5,2);
  v_activity_id uuid;
BEGIN
  IF p_source_table NOT IN ('applications','event_applications') OR p_source_id IS NULL THEN
    RAISE EXCEPTION 'invalid activity source' USING ERRCODE = '22023';
  END IF;

  IF p_source_table = 'applications' THEN
    SELECT a.user_id, a.status, a.hub_id, a.completion_country_code, a.completion_value,
           a.complexity_score, a.completed_by, a.completed_at
      INTO v_profile_id, v_status, v_hub_id, v_country, v_value, v_complexity, v_completed_by, v_completed_at
    FROM public.applications a WHERE a.id = p_source_id;
    IF NOT FOUND OR v_status <> 'completed' THEN RETURN NULL; END IF;
    v_label := COALESCE(NULLIF(btrim(v_hub_id), ''), 'Completed tour');

    IF NULLIF(btrim(v_country), '') IS NULL THEN
      SELECT upper(COALESCE(NULLIF(d.country_code,''), CASE WHEN d.code ~* '^[A-Z]{2}$' THEN d.code END))
        INTO v_country
      FROM public.game_destinations d
      WHERE d.id = v_hub_id OR d.code = v_hub_id
      ORDER BY (d.id = v_hub_id) DESC
      LIMIT 1;
    END IF;
  ELSE
    SELECT ea.user_id, ea.status, ea.event_id, ea.completion_country_code, ea.completion_value,
           ea.complexity_score, ea.completed_by, ea.completed_at
      INTO v_profile_id, v_status, v_event_id, v_country, v_value, v_complexity, v_completed_by, v_completed_at
    FROM public.event_applications ea WHERE ea.id = p_source_id;
    IF NOT FOUND OR v_status <> 'completed' THEN RETURN NULL; END IF;

    SELECT e.title, e.country_code INTO v_event_title, v_event_country
    FROM public.global_events e WHERE e.id = v_event_id;
    v_label := COALESCE(NULLIF(btrim(v_event_title), ''), 'Completed club event');
    v_country := COALESCE(NULLIF(btrim(v_country), ''), v_event_country);
  END IF;

  v_country := upper(NULLIF(btrim(v_country), ''));
  IF v_country !~ '^[A-Z]{2}$' THEN v_country := NULL; END IF;

  SELECT COALESCE(p.reliability, 100)::numeric(5,2)
    INTO v_reliability
  FROM public.profiles p WHERE p.id = v_profile_id;
  v_reliability := COALESCE(v_reliability, 100);

  IF p_source_table = 'applications' THEN
    INSERT INTO public.resident_activities(
      profile_id, activity_type, source_application_id, source_label, destination_code,
      commercial_value, complexity_score, reliability_snapshot, completed_by, completed_at
    ) VALUES (
      v_profile_id, 'tour', p_source_id, v_label, v_country,
      GREATEST(COALESCE(v_value,0),0), GREATEST(1,LEAST(3,COALESCE(v_complexity,1))),
      v_reliability, v_completed_by, COALESCE(v_completed_at, now())
    ) ON CONFLICT (source_application_id) DO NOTHING
    RETURNING id INTO v_activity_id;

    IF v_activity_id IS NULL THEN
      SELECT a.id INTO v_activity_id FROM public.resident_activities a WHERE a.source_application_id = p_source_id;
    END IF;
  ELSE
    INSERT INTO public.resident_activities(
      profile_id, activity_type, source_event_application_id, source_label, destination_code,
      commercial_value, complexity_score, reliability_snapshot, completed_by, completed_at
    ) VALUES (
      v_profile_id, 'event', p_source_id, v_label, v_country,
      GREATEST(COALESCE(v_value,0),0), GREATEST(1,LEAST(3,COALESCE(v_complexity,1))),
      v_reliability, v_completed_by, COALESCE(v_completed_at, now())
    ) ON CONFLICT (source_event_application_id) DO NOTHING
    RETURNING id INTO v_activity_id;

    IF v_activity_id IS NULL THEN
      SELECT a.id INTO v_activity_id FROM public.resident_activities a WHERE a.source_event_application_id = p_source_id;
    END IF;
  END IF;

  IF v_activity_id IS NOT NULL THEN
    PERFORM public.resident_process_activity(v_activity_id);
  END IF;
  RETURN v_activity_id;
END;
$function$;

CREATE OR REPLACE FUNCTION public.process_completed_activity()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER
SET search_path TO ''
AS $function$
BEGIN
  IF NEW.status IS DISTINCT FROM 'completed' THEN RETURN NEW; END IF;
  IF TG_OP = 'UPDATE' AND OLD.status = 'completed' THEN RETURN NEW; END IF;
  PERFORM public.resident_process_completed_activity_row(TG_TABLE_NAME, NEW.id);
  RETURN NEW;
END;
$function$;

-- 5. A manual passport stamp now produces its country-bonus ledger row once.
CREATE OR REPLACE FUNCTION public.resident_process_passport_stamp()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_country_count integer;
BEGIN
  -- Activity completion uses resident_process_activity(), which already writes this event key.
  IF NEW.activity_id IS NOT NULL THEN RETURN NEW; END IF;

  IF COALESCE(NEW.points_awarded,0) > 0 THEN
    INSERT INTO public.resident_score_events(profile_id, activity_id, event_key, category, points, reason, metadata)
    VALUES (
      NEW.profile_id, NULL, 'stamp:' || NEW.profile_id::text || ':' || upper(NEW.country_code),
      'stamp', NEW.points_awarded,
      'First passport stamp: ' || COALESCE(NULLIF(NEW.country_title,''), upper(NEW.country_code)),
      jsonb_build_object('source','resident_passport_stamps','stamp_id',NEW.id,'country_code',upper(NEW.country_code))
    ) ON CONFLICT (event_key) DO NOTHING;
  END IF;

  PERFORM public.resident_award_achievement(
    NEW.profile_id, 'first_country_stamp', 'First Passport Stamp', NULL, 'achievement_first_stamp'
  );

  SELECT count(*)::integer INTO v_country_count
  FROM public.resident_passport_stamps s WHERE s.profile_id = NEW.profile_id;
  IF v_country_count >= 5 THEN
    PERFORM public.resident_award_achievement(
      NEW.profile_id, 'five_countries', 'Five Countries', NULL, 'achievement_five_countries'
    );
  END IF;

  PERFORM public.resident_refresh_metrics(NEW.profile_id);
  RETURN NEW;
END;
$function$;

