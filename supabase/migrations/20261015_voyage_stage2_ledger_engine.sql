-- Prevent ledger rows from being edited/deleted in normal operations. FK cascades on profile
-- deletion are allowed to proceed (nested RI trigger depth); inserts are always permitted.
CREATE OR REPLACE FUNCTION public.resident_score_events_reject_mutation()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER
SET search_path TO ''
AS $function$
BEGIN
  IF pg_trigger_depth() > 1 OR current_setting('voyage.gamification_maintenance', true) = 'on' THEN
    IF TG_OP = 'DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
  END IF;
  RAISE EXCEPTION 'resident_score_events is an immutable ledger; append a compensating adjustment instead'
    USING ERRCODE = '55000';
END;
$function$;

