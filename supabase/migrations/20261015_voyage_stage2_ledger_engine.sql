-- VOYAGE Master Blueprint · Stage 2: Backend Ledger & Passport Stamp Repair
-- Target: PostgreSQL / Supabase. Safe to re-run. Wraps all changes in one transaction.
-- Important: game_attendance is the table written by the current admin stamping UI.
-- Historical attendance scores are imported once into resident_score_events and reconciled
-- against legacy resident_metrics baselines so Influence is not double-counted.

BEGIN;
SET LOCAL search_path = public, pg_catalog;
SET LOCAL lock_timeout = '8s';

DO $guard$
BEGIN
  IF to_regclass('public.profiles') IS NULL
     OR to_regclass('public.applications') IS NULL
     OR to_regclass('public.event_applications') IS NULL
     OR to_regclass('public.global_events') IS NULL
     OR to_regclass('public.game_attendance') IS NULL
     OR to_regclass('public.game_destinations') IS NULL
     OR to_regclass('public.game_combos') IS NULL THEN
    RAISE EXCEPTION 'VOYAGE Stage 2 requires profiles, applications, event_applications, global_events, game_attendance, game_destinations and game_combos';
  END IF;
END;
$guard$;

-- 1. Ensure the ledger/passport tables exist without replacing existing rows.
CREATE TABLE IF NOT EXISTS public.resident_activities (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  profile_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  activity_type text NOT NULL CHECK (activity_type IN ('tour','event')),
  source_application_id uuid REFERENCES public.applications(id),
  source_event_application_id uuid REFERENCES public.event_applications(id),
  source_label text NOT NULL,
  destination_code text,
  commercial_value numeric(12,2) NOT NULL DEFAULT 0 CHECK (commercial_value >= 0 AND commercial_value <= 100000000),
  complexity_score numeric(4,2) NOT NULL DEFAULT 1 CHECK (complexity_score >= 1 AND complexity_score <= 3),
  reliability_snapshot numeric(5,2) NOT NULL DEFAULT 100 CHECK (reliability_snapshot >= 0 AND reliability_snapshot <= 100),
  points_awarded integer NOT NULL DEFAULT 0 CHECK (points_awarded >= 0),
  completed_by uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  completed_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((source_application_id IS NOT NULL AND source_event_application_id IS NULL) OR (source_application_id IS NULL AND source_event_application_id IS NOT NULL)),
  CHECK (destination_code IS NULL OR destination_code ~ '^[A-Z]{2}$')
);

