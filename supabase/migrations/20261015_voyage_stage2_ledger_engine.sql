-- 9. Reconcile legacy snapshots once. game_base_influence already included the eligible
--    attendance/combo values; those values move into the ledger without inflating Influence.
--    Inactive/out-of-scope historical visits now get their own ledger rows instead of remaining hidden.
DO $legacy_reconcile$
DECLARE v_first_run integer;
BEGIN
  INSERT INTO public.resident_gamification_migrations(migration_key)
  VALUES ('stage2_legacy_reconciliation_v1')
  ON CONFLICT (migration_key) DO NOTHING;
  GET DIAGNOSTICS v_first_run = ROW_COUNT;

  IF v_first_run = 1 THEN
    INSERT INTO public.resident_metrics(profile_id)
    SELECT p.id FROM public.profiles p WHERE p.role = 'resident'
    ON CONFLICT (profile_id) DO NOTHING;

    WITH eligible_attendance AS (
      SELECT ga.profile_id,
             count(*)::integer AS legacy_stamps_count,
             count(DISTINCT ga.destination_id)::integer AS legacy_destinations_count,
             COALESCE(sum(round(COALESCE(ga.points,d.points)::numeric * COALESCE(ga.multiplier,d.multiplier) * public.game_visit_factor(ga.visit_number)))::integer,0)::integer AS legacy_stamp_points
      FROM public.game_attendance ga
      JOIN public.game_destinations d ON d.id = ga.destination_id
      WHERE d.active AND d.region = ANY(ARRAY['mideast','asia','europe','namerica']::text[])
      GROUP BY ga.profile_id
    ), combo_defs AS (
      SELECT c.id,c.destination_ids,
             GREATEST(1, LEAST(COALESCE(c.required_count, cardinality(c.destination_ids)), cardinality(c.destination_ids))) AS needed,
             GREATEST(COALESCE(c.bonus,0),0)::integer AS legacy_bonus
      FROM public.game_combos c WHERE c.active AND cardinality(c.destination_ids)>0
    ), legacy_combos AS (
      SELECT ga.profile_id,
             1::integer AS legacy_combos_completed,
             COALESCE(sum(cd.legacy_bonus),0)::integer AS legacy_combo_points
      FROM combo_defs cd
      JOIN public.game_attendance ga ON ga.destination_id = ANY(cd.destination_ids)
      JOIN public.game_destinations gd ON gd.id=ga.destination_id
        AND gd.active AND gd.region = ANY(ARRAY['mideast','asia','europe','namerica']::text[])
      GROUP BY ga.profile_id,cd.id,cd.needed
      HAVING count(DISTINCT ga.destination_id) >= cd.needed
    ), combo_by_profile AS (
      SELECT profile_id, sum(legacy_combos_completed)::integer AS legacy_combos_completed,
             sum(legacy_combo_points)::integer AS legacy_combo_points
      FROM legacy_combos GROUP BY profile_id
    )
    UPDATE public.resident_metrics rm
    SET legacy_total_points = GREATEST(0, rm.legacy_total_points
          - COALESCE(ea.legacy_stamp_points,0) - COALESCE(cb.legacy_combo_points,0)),
        legacy_stamp_points = GREATEST(0, rm.legacy_stamp_points - COALESCE(ea.legacy_stamp_points,0)),
        legacy_stamps_count = GREATEST(0, rm.legacy_stamps_count - COALESCE(ea.legacy_stamps_count,0)),
        legacy_destinations_count = GREATEST(0, rm.legacy_destinations_count - COALESCE(ea.legacy_destinations_count,0)),
        legacy_combo_points = GREATEST(0, rm.legacy_combo_points - COALESCE(cb.legacy_combo_points,0)),
        legacy_combos_completed = GREATEST(0, rm.legacy_combos_completed - COALESCE(cb.legacy_combos_completed,0))
    FROM public.profiles p
    LEFT JOIN eligible_attendance ea ON ea.profile_id=p.id
    LEFT JOIN combo_by_profile cb ON cb.profile_id=p.id
    WHERE rm.profile_id=p.id AND p.role='resident';
  END IF;
END;
$legacy_reconcile$;

